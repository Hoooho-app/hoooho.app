for(const model of ['boy','girl'] as const) test(`all ${model} dictionary regions and applicable fine entries are reachable, assets and keyboard back`,async({page},info)=>{
  test.skip(info.project.name!=='iphone-se','Complete dictionary traversal on SE; responsive flow covered in each project')
  const form=await prepare(page,`body-${model}`);await form.locator('.child-body-open').click()
  const p=picker(page);await expect(p.locator(`[data-asset="assets/${model}-front.png"]`)).toBeVisible()
  await snapshot(page,`${model}-front`,info.project.name)
  await p.getByRole('button',{name:'背面',exact:true}).click()
  await expect(p.locator(`[data-asset="assets/${model}-back.png"]`)).toBeVisible()
  await snapshot(page,`${model}-back`,info.project.name)
  let reached=0
  for(const region of source.regions){
    await openRegion(p,region.id)
    const expected=region.items.filter(i=>i.sex.includes(model)).map(i=>i.id)
    await expect(p.locator('[data-location-id]')).toHaveCount(expected.length)
    expect(await p.locator('[data-location-id]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('data-location-id')))).toEqual(expect.arrayContaining(expected))
    expect(await p.locator('[data-location-id]').count()).toBe(expected.length)
    expect(await p.locator('[data-location-id]').evaluateAll(nodes=>nodes.every(node=>node.getBoundingClientRect().height>=44))).toBe(true)
    await noOverflow(page,p)
    await item(p,expected.at(-1)!).click();await expect(item(p,expected.at(-1)!)).toHaveAttribute('aria-pressed','true')
    await item(p,expected.at(-1)!).click()
    if(['face','hand_left','foot_right'].includes(region.id))await snapshot(page,`${model}-${region.id}`,info.project.name)
    reached+=expected.length
    await back(p)
  }
  expect(reached).toBe(model==='boy'?561:562)
  await openRegion(p,'face');await page.keyboard.press('Escape');await expect(p.locator('[data-region-id="face"]')).toBeAttached()
  await page.keyboard.press('Escape');await expect(p).toHaveCount(0);await expect(form).toBeVisible()
})

