async function prepare(page:Page,memberId='body-girl'){
  memberId = `${memberId}-${test.info().project.name}`
  page.on('pageerror',error=>{throw error})
  const authToken=token()
  await page.addInitScript(({authToken,memberId,accountId})=>{
    sessionStorage.setItem('hoooho-auth-token',authToken)
    if(!sessionStorage.getItem('body-locator-initialized')){
      localStorage.setItem('hoooho-app',JSON.stringify({state:{authUser:{id:accountId},currentMemberId:memberId,members:[],profile:null},version:5}))
      sessionStorage.setItem('body-locator-initialized','true')
    }
  },{authToken,memberId,accountId})
  await page.goto('/health-events')
  await page.getByRole('button',{name:'记一下',exact:true}).click()
  await page.getByRole('dialog',{name:'记一下',exact:true}).getByRole('button',{name:'记录症状',exact:true}).click()
  const form=page.getByRole('dialog',{name:'记录症状',exact:true})
  await expect(form).toBeVisible()
  return form
}
const picker=(page:Page)=>page.getByRole('dialog',{name:'身体部位定位器',exact:true})
const item=(p:Locator,id:string)=>p.locator(`[data-location-id="${id}"]`)
async function openRegion(p:Locator,id:string){await p.locator(`[data-region-id="${id}"]`).click()}
async function back(p:Locator){await p.getByRole('button',{name:'返回全身',exact:true}).first().click();await expect(p.locator('[data-region-id="face"]')).toBeAttached()}
async function snapshot(page:Page,name:string,project:string){
  if(await picker(page).count()) await picker(page).locator('.hoho-bottom-sheet__body').evaluate(el=>{el.scrollTop=0})
  const dir=`outputs/body-locator/${process.env.BODY_EVIDENCE || 'local'}/${project}`
  await mkdir(dir,{recursive:true});await page.screenshot({path:`${dir}/${name}.png`})
}
