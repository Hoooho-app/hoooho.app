import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'
import { FAMILY_WORKSPACE_PATH } from '../../shared/family-workspace.mjs'

test('asset photos upload without parsing, preview and zoom, download originals and manual OCR, and keep dates and family access on phones', async ({ page, context, browser }) => {
  const errors: string[] = [], parseRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().endsWith('/parse')) parseRequests.push(request.url()) })
  await page.goto(`${FAMILY_WORKSPACE_PATH}#assets/cash`)
  await page.getByRole('tab', { name: '管理员登录' }).click()
  await page.getByLabel('管理员邮箱', { exact: true }).fill('ray@example.test')
  await page.getByRole('button', { name: '获取邮箱验证码', exact: true }).click()
  await expect(page.getByText('请查收验证码', { exact: true })).toBeVisible()
  const delivery = JSON.parse(await readFile(path.resolve('.codex-tmp/family-workspace-browser/test-email.json'), 'utf8'))
  await page.locator('#family-code').fill(delivery.otp)
  await page.getByRole('button', { name: '登录并管理家庭空间', exact: true }).click()
  await page.getByRole('button', { name: '新增资产', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '新增资产', exact: true })
  await editor.getByLabel('资产名称', { exact: true }).fill('附件测试银行卡')
  await editor.getByLabel('当前余额或估值（元）', { exact: true }).fill('300.25')
  await editor.getByLabel('取得 / 开卡日期', { exact: true }).fill('2024-01-20')
  await editor.getByRole('combobox', { name: '有效期精度', exact: true }).selectOption('month')
  await editor.getByLabel('有效期 / 到期日', { exact: true }).fill('2028-10')
  await editor.getByLabel('提前提示天数', { exact: true }).fill('60')
  await editor.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(editor).toHaveCount(0)
  await expect(page.getByText('有效期至：2028-10 月底', { exact: true })).toBeVisible()
  const assetRow = page.getByRole('row').filter({ has: page.getByRole('button', { name: '编辑附件测试银行卡', exact: true }) })
  const dateBox = await assetRow.locator('.family-asset-dates').boundingBox(), actionBox = await assetRow.locator('td').last().boundingBox()
  expect(dateBox!.x + dateBox!.width).toBeLessThanOrEqual(actionBox!.x)
  let files = page.getByRole('region', { name: '附件测试银行卡附件资料', exact: true })
  await files.locator('summary').click()
  const png = await sharp(Buffer.from('<svg width="480" height="280" xmlns="http://www.w3.org/2000/svg"><rect width="480" height="280" fill="#e2ece9"/><text x="35" y="80" fill="#213b34" font-size="25">BROWSER TEST CARD</text><text x="35" y="150" fill="#213b34" font-size="25">VALID THRU 10/28</text></svg>')).png().toBuffer()
  await files.locator('input[type=file]').setInputFiles([{ name: '银行卡正面.png', mimeType: 'image/png', buffer: png }, { name: '银行卡背面.png', mimeType: 'image/png', buffer: png }])
  await expect(files.locator('summary')).toContainText('2 张')
  await expect(files.getByText('已上传 2 张，未自动解析。', { exact: true })).toBeVisible()
  expect(parseRequests).toHaveLength(0)
  await files.getByRole('button', { name: '查看银行卡正面.png', exact: true }).click()
  const preview = page.getByRole('dialog', { name: '资产附件预览', exact: true })
  await expect(preview.getByRole('img', { name: '银行卡正面.png', exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '放大', exact: true }).click()
  await preview.getByRole('button', { name: '放大', exact: true }).click()
  await expect(preview.getByText('200%', { exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '下一张', exact: true }).click()
  await expect(preview.getByRole('heading', { name: '银行卡背面.png', exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '上一张', exact: true }).click()
  const originalDownload = page.waitForEvent('download')
  await preview.getByRole('button', { name: '下载原图', exact: true }).click()
  const original = await originalDownload
  expect(original.suggestedFilename()).toBe('银行卡正面.png')
  expect(await readFile((await original.path())!)).toEqual(png)
  await preview.getByRole('button', { name: '关闭资产附件预览', exact: true }).click()
  let first = true
  await page.route('**/finance/assets/*/attachments/*/parse', async route => {
    if (first) { first = false; await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '图片解析暂未完成，原图已保留，请稍后重试。' } }) }) }
    else await route.continue()
  })
  await files.getByRole('button', { name: '解析图片', exact: true }).first().click()
  await expect(files.getByText('图片解析暂未完成，原图已保留，请稍后重试。', { exact: true })).toBeVisible()
  await files.getByRole('button', { name: '解析图片', exact: true }).first().click()
  await expect(preview.getByLabel('解析文字', { exact: true })).toHaveValue(/BROWSER TEST CARD/)
  const textDownload = page.waitForEvent('download')
  await preview.getByRole('button', { name: '下载 TXT', exact: true }).click()
  const text = await textDownload
  expect(text.suggestedFilename()).toBe('银行卡正面-解析.txt')
  expect(await readFile((await text.path())!, 'utf8')).toContain('有效期 10/28')
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await preview.getByRole('button', { name: '复制文字', exact: true }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toContain('BROWSER TEST CARD')
  await preview.getByRole('button', { name: '关闭资产附件预览', exact: true }).click()
  await page.reload()
  files = page.getByRole('region', { name: '附件测试银行卡附件资料', exact: true })
  await expect(files.locator('summary')).toContainText('2 张')
  await expect(page.getByText('有效期至：2028-10 月底', { exact: true })).toBeVisible()
  await files.locator('summary').click()
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/asset-attachments-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await files.getByRole('button', { name: '查看银行卡正面.png', exact: true }).click()
  await expect(preview.getByLabel('解析文字', { exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '放大', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/asset-preview-mobile.png', fullPage: true })
  await preview.getByRole('button', { name: '关闭资产附件预览', exact: true }).click()
  await page.getByRole('button', { name: '编辑附件测试银行卡', exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑资产', exact: true })
  await edit.getByRole('combobox', { name: '有效期精度', exact: true }).selectOption('day')
  await edit.getByLabel('有效期 / 到期日', { exact: true }).fill('2024-01-01')
  await edit.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(edit.getByText('到期日期不能早于起始日期。', { exact: true })).toBeVisible()
  await edit.getByLabel('有效期 / 到期日', { exact: true }).fill('2024-01-21')
  await edit.getByRole('button', { name: '保存记录', exact: true }).click()
  await expect(edit).toHaveCount(0)
  await expect(page.getByText(/已到期 \d+ 天/)).toBeVisible()
  const origin = 'http://127.0.0.1:4197', headers = { Origin: origin, 'X-Hoooho-Family': '1' }
  const codeResponse = await context.request.post(`${origin}${FAMILY_WORKSPACE_PATH}/api/codes`, { data: { label: '附件测试家人' }, headers })
  expect(codeResponse.ok()).toBe(true)
  const code = await codeResponse.json()
  const mobile = await browser.newContext({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' })
  const phone = await mobile.newPage()
  phone.on('pageerror', error => errors.push(error.message))
  await phone.goto(`${origin}${FAMILY_WORKSPACE_PATH}#assets/cash`)
  await phone.locator('#family-code').fill(code.loginCode)
  await phone.getByRole('button', { name: '进入家庭空间', exact: true }).click()
  const familyFiles = phone.getByRole('region', { name: '附件测试银行卡附件资料', exact: true })
  await familyFiles.locator('summary').click()
  await expect(familyFiles.getByRole('button', { name: '上传照片', exact: true })).toHaveCount(0)
  await expect(familyFiles.getByRole('button', { name: /删除附件/ })).toHaveCount(0)
  await familyFiles.getByRole('button', { name: '解析图片', exact: true }).click()
  await expect(phone.getByLabel('解析文字', { exact: true })).toHaveValue(/BROWSER TEST CARD/)
  await phone.getByRole('dialog', { name: '资产附件预览', exact: true }).getByRole('button', { name: '关闭资产附件预览', exact: true }).click()
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await phone.screenshot({ path: '.codex-tmp/family-workspace-results/asset-files-member-mobile.png', fullPage: true })
  const snapshot = await (await context.request.get(`${origin}${FAMILY_WORKSPACE_PATH}/api/finance`)).json()
  const file = snapshot.attachments.find((file: { name: string }) => file.name === '银行卡正面.png')
  await context.request.post(`${origin}${FAMILY_WORKSPACE_PATH}/api/codes/${code.id}/revoke`, { data: {}, headers })
  expect((await mobile.request.get(`${origin}${FAMILY_WORKSPACE_PATH}/api/finance/assets/${file.assetId}/attachments/${file.id}/original`)).status()).toBe(401)
  await mobile.close()
  await files.getByRole('button', { name: '删除附件银行卡正面.png', exact: true }).click()
  await page.getByRole('button', { name: '确认删除附件', exact: true }).click()
  await expect(files.locator('summary')).toContainText('1 张')
  const latest = await (await context.request.get(`${origin}${FAMILY_WORKSPACE_PATH}/api/finance`)).json()
  latest.data.assets = latest.data.assets.filter((asset: { id: string }) => asset.id !== file.assetId)
  expect((await context.request.post(`${origin}${FAMILY_WORKSPACE_PATH}/api/finance`, { data: { revision: latest.revision, data: latest.data }, headers })).ok()).toBe(true)
  expect(errors).toEqual([])
})
