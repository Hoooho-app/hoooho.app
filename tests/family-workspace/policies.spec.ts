import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { FAMILY_WORKSPACE_PATH } from '../../shared/family-workspace.mjs'
import { policyModuleIds } from '../../shared/family-policies.mjs'

test('all nine pinned policies render four real views, save shared content and preserve permissions and stale edits', async ({ page, browser }) => {
  const errors: string[] = []
  const viewLink = (name: string) => page.getByRole('complementary', { name: '三级目录', exact: true }).getByRole('link', { name, exact: true })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(FAMILY_WORKSPACE_PATH)
  await page.getByRole('tab', { name: '管理员登录', exact: true }).click()
  await page.getByLabel('管理员邮箱', { exact: true }).fill('ray@example.test')
  await page.getByRole('button', { name: '获取邮箱验证码', exact: true }).click()
  await expect(page.getByText('请查收验证码', { exact: true })).toBeVisible()
  const delivery = JSON.parse(await readFile(path.resolve('.codex-tmp/family-workspace-browser-4207/test-email.json'), 'utf8'))
  await page.locator('#family-code').fill(delivery.otp)
  await page.getByRole('button', { name: '登录并管理家庭空间', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的空间', exact: true })).toBeVisible()
  const primary = page.getByRole('navigation', { name: '家庭空间导航' })
  const titles = ['家庭收支与预算', '资产负债与投资', '税务法律与传承', '日程与生活安排', '居所物品与家政', '健康与照护', '子女教育与成长', '风险安全与应急', '家庭治理与关系']
  for (const [index, title] of titles.entries()) {
    await primary.getByRole('button', { name: title, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`#${policyModuleIds[index]}/policy/text$`))
    const secondary = page.getByRole('navigation', { name: `${title}二级菜单` })
    await expect(secondary.getByRole('link').first()).toContainText('制度')
    await expect(secondary.getByRole('link').first()).toContainText('置顶')
    await expect(secondary.getByRole('link').first()).toHaveAttribute('aria-current', 'page')
    await expect(page.getByText('V0.1 · 建议初稿', { exact: true })).toBeVisible()
    await expect(page.locator('.family-policy-section')).toHaveCount(4)
    for (const view of ['执行流程', '制度脑图', '分工与检查', '制度正文']) {
      await viewLink(view).click()
      await expect(page.getByRole('region', { name: view, exact: true })).toBeVisible()
    }
  }
  await primary.getByRole('button', { name: '家庭收支与预算', exact: true }).click()
  await viewLink('执行流程').click()
  await expect(page.locator('.family-policy-flow-branches > div')).toHaveCount(2)
  await page.screenshot({ path: '.codex-tmp/family-policy-results/flow-desktop.png', fullPage: true })
  await viewLink('制度脑图').click()
  await page.getByRole('button', { name: '02 收支怎么记', exact: true }).click()
  await expect(viewLink('制度正文')).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('#family-policy-section-1')).toBeFocused()
  await page.getByRole('button', { name: '编辑制度', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '编辑本类制度', exact: true })
  await editor.getByLabel('第 1 节条款', { exact: true }).fill('每月初由爸爸与妈妈共同核对预算。\n共同支出及时记录。')
  await editor.getByLabel('办理与归档', { exact: true }).fill('付款后由爸爸核对凭证并归档')
  await editor.getByLabel('分工 1 · 主负责人', { exact: true }).fill('爸爸与妈妈')
  await editor.getByRole('button', { name: '保存制度', exact: true }).click()
  await expect(editor).not.toBeVisible()
  await expect(page.getByText('每月初由爸爸与妈妈共同核对预算。', { exact: true })).toBeVisible()
  await expect(page.getByText('待家庭确认', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('V1 · 家庭版本', { exact: true })).toBeVisible()
  await viewLink('执行流程').click()
  await expect(page.getByText('付款后由爸爸核对凭证并归档', { exact: true })).toBeVisible()
  await viewLink('制度脑图').click()
  await expect(page.getByText('每月初由爸爸与妈妈共同核对预算。', { exact: true })).toBeVisible()
  await viewLink('分工与检查').click()
  await expect(page.getByRole('cell', { name: '爸爸与妈妈', exact: false })).toBeVisible()
  await page.screenshot({ path: '.codex-tmp/family-policy-results/checks-desktop.png', fullPage: true })

  await page.getByRole('button', { name: '编辑制度', exact: true }).click()
  await editor.getByLabel('制度目标', { exact: true }).fill('冲突时这段正在填写的内容应保留。')
  const current = await (await page.request.get(`${FAMILY_WORKSPACE_PATH}/api/policies/finances`)).json()
  const concurrent = await page.request.post(`${FAMILY_WORKSPACE_PATH}/api/policies/finances`, { data: { ...current, document: { ...current.document, purpose: '另一窗口保存的目标' } }, headers: { Origin: 'http://127.0.0.1:4207', 'X-Hoooho-Family': '1' } })
  expect(concurrent.status()).toBe(200)
  await editor.getByRole('button', { name: '保存制度', exact: true }).click()
  await expect(editor.getByText(/本制度已在另一窗口更新/)).toBeVisible()
  await expect(editor.getByLabel('制度目标', { exact: true })).toHaveValue('冲突时这段正在填写的内容应保留。')
  await editor.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '继续编辑', exact: true }).click()
  await expect(editor.getByLabel('制度目标', { exact: true })).toHaveValue('冲突时这段正在填写的内容应保留。')
  await editor.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '放弃修改', exact: true }).click()
  await page.getByRole('button', { name: '重新载入制度', exact: true }).click()
  await expect(page.getByText('另一窗口保存的目标', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '家人访问管理', exact: true }).click()
  await page.getByLabel('家人称呼').fill('制度阅读家人')
  await page.getByRole('button', { name: '生成 30 天登录码', exact: true }).click()
  const code = await page.getByLabel('登录码（仅本次显示）', { exact: true }).inputValue()
  const member = await browser.newContext({ baseURL: 'http://127.0.0.1:4207', viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' })
  const phone = await member.newPage()
  phone.on('pageerror', error => errors.push(error.message))
  await phone.goto(FAMILY_WORKSPACE_PATH)
  await phone.locator('#family-code').fill(code)
  await phone.getByRole('button', { name: '进入家庭空间', exact: true }).click()
  await phone.getByRole('button', { name: '打开导航', exact: true }).click()
  await phone.getByRole('navigation', { name: '家庭空间导航' }).getByRole('button', { name: '家庭收支与预算', exact: true }).click()
  await expect(phone.getByText('另一窗口保存的目标', { exact: true })).toBeVisible()
  await expect(phone.getByRole('button', { name: '编辑制度', exact: true })).toHaveCount(0)
  const forbidden = await member.request.post(`${FAMILY_WORKSPACE_PATH}/api/policies/finances`, { data: current, headers: { Origin: 'http://127.0.0.1:4207', 'X-Hoooho-Family': '1' } })
  expect(forbidden.status()).toBe(403)
  for (const view of ['制度正文', '执行流程', '制度脑图', '分工与检查']) {
    await phone.getByRole('complementary', { name: '三级目录', exact: true }).getByRole('link', { name: view, exact: true }).click()
    expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await phone.screenshot({ path: `.codex-tmp/family-policy-results/member-${view}.png`, fullPage: true })
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`${FAMILY_WORKSPACE_PATH}#education/policy`)
  await page.getByRole('button', { name: '编辑制度', exact: true }).click()
  await expect(editor).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.codex-tmp/family-policy-results/editor-mobile.png', fullPage: true })
  await editor.getByRole('button', { name: '关闭编辑', exact: true }).click()
  await member.close()
  expect(errors).toEqual([])
})
