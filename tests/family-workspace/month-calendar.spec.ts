import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { randomUUID } from 'node:crypto'
import { FAMILY_WORKSPACE_PATH as workspace } from '../../shared/family-workspace.mjs'
import { emptyFinanceData } from '../../shared/family-finance.mjs'

test('compact month, grouped colors, date and month-only creation, real persistence, source links and phone reading', async ({ page, browser, baseURL }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(workspace)
  await page.getByRole('tab', { name: '管理员登录' }).click()
  await page.getByLabel('管理员邮箱', { exact: true }).fill('ray@example.test')
  await page.getByRole('button', { name: '获取邮箱验证码', exact: true }).click()
  await expect(page.getByText('请查收验证码', { exact: true })).toBeVisible()
  const delivery = JSON.parse(await readFile(path.resolve('.codex-tmp/family-workspace-browser-4217/test-email.json'), 'utf8'))
  await page.locator('#family-code').fill(delivery.otp)
  await page.getByRole('button', { name: '登录并管理家庭空间', exact: true }).click()
  const calendar = page.getByRole('region', { name: '家庭月历', exact: true })
  await expect(calendar).toBeVisible()
  await expect(calendar.getByText(/0 项安排 · 0 项日期待定/)).toBeVisible()
  expect(await page.locator('.family-month-grid tbody tr').count()).toBeLessThanOrEqual(6)
  await page.getByRole('button', { name: '添加安排', exact: true }).click()
  await page.getByLabel('添加到对应页面').selectOption('finances/budget')
  await page.getByRole('button', { name: '去添加本月安排', exact: true }).click()
  await expect(page).toHaveURL(/#finances\/budget\/monthly$/)
  const month = await page.getByLabel('安排月份', { exact: true }).inputValue()
  await expect(page.getByLabel('指定日期或日期范围', { exact: false })).not.toBeChecked()
  await page.getByLabel('安排名称', { exact: true }).fill('本月家庭资金安排')
  await page.getByLabel('准备事项与备注（可选）', { exact: true }).fill('先整理全家的现金流。'.repeat(60))
  await page.getByRole('button', { name: '保存安排', exact: true }).click()
  await expect(page.getByText('已保存到首页月历。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看首页月历', exact: true }).click()
  await expect(page.locator('.family-month-undated').getByRole('button', { name: '本月家庭资金安排', exact: true })).toBeVisible()
  await calendar.getByRole('button', { name: '下个月', exact: true }).click()
  await expect(page.locator('.family-month-undated').getByText('本月家庭资金安排', { exact: true })).toHaveCount(0)
  await calendar.getByRole('button', { name: '上个月', exact: true }).click()
  await expect(page.locator('.family-month-undated').getByRole('button', { name: '本月家庭资金安排', exact: true })).toBeVisible()
  const date = `${month}-21`
  await page.getByRole('button', { name: `${date}，0 项安排`, exact: true }).click()
  await page.getByLabel('添加到对应页面').selectOption('schedule/travel')
  await page.getByRole('button', { name: '去添加当天安排', exact: true }).click()
  await expect(page).toHaveURL(/#schedule\/travel\/holidays$/)
  await expect(page.getByLabel('开始日期', { exact: true })).toHaveValue(date)
  await page.getByLabel('安排名称', { exact: true }).fill('周末亲子出游')
  await page.getByLabel('负责人（可选）', { exact: true }).fill('爸爸')
  await page.getByRole('button', { name: '保存安排', exact: true }).click()
  await expect(page.getByText('已保存到首页月历。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看首页月历', exact: true }).click()
  await page.reload()
  await expect(calendar.getByRole('button', { name: `${date} 周末亲子出游，进入对应页面`, exact: true })).toBeVisible()
  // An older saved parent name stays discoverable and editable after the directory merge.
  const older = await (await page.request.get(`${baseURL}${workspace}/api/arrangements`)).json()
  const legacy = older.plans.find((plan: { title: string }) => plan.title === '本月家庭资金安排')
  expect((await page.request.post(`${baseURL}${workspace}/api/arrangements`, { headers: { Origin: baseURL!, 'X-Hoooho-Family': '1' }, data: { action: 'save', revision: older.revision, plan: { ...legacy, page: 'cashflow' } } })).ok()).toBe(true)
  await page.reload()
  await page.locator('.family-month-undated').getByRole('button', { name: '本月家庭资金安排', exact: true }).click()
  await expect(page).toHaveURL(/#finances\/budget\/monthly$/)
  await expect(page.getByLabel('安排名称', { exact: true })).toHaveValue('本月家庭资金安排')
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '查看首页月历', exact: true }).click()

  const post = (route: string, data: unknown) => page.request.post(`${baseURL}${workspace}/api${route}`, { headers: { Origin: baseURL!, 'X-Hoooho-Family': '1' }, data })
  let snapshot = await (await page.request.get(`${baseURL}${workspace}/api/arrangements`)).json()
  for (let index = 0; index < 4; index++) {
    const response = await post('/arrangements', { action: 'save', revision: snapshot.revision, plan: { id: randomUUID(), module: 'education', page: 'activities', title: `亲子活动 ${index + 1}`, month, startDate: date, endDate: date, status: 'pending', owner: '爸爸', note: '' } })
    expect(response.status()).toBe(200); snapshot = await response.json()
  }
  const finances = await (await page.request.get(`${baseURL}${workspace}/api/finance`)).json()
  const financeData = emptyFinanceData()
  financeData.debts.push({ id: randomUUID(), name: '家庭信用卡', owner: '家庭共同', note: '', category: 'credit', balance: 500, apr: null, monthlyPayment: 500, creditLimit: 10000, dueDate: date })
  expect((await post('/finance', { revision: finances.revision, data: financeData })).status()).toBe(200)
  await page.reload()
  await expect(calendar.getByRole('button', { name: `查看 ${date} 的全部 6 项安排`, exact: true })).toBeVisible()
  const tree = page.getByRole('complementary', { name: '按类别分组的本月安排', exact: true })
  await expect(tree.getByText('亲子活动 4', { exact: true })).toBeVisible()
  const dimensions = await page.locator('.family-month-grid').boundingBox()
  expect(dimensions!.height).toBeLessThan(650)
  const colors = await page.evaluate(() => {
    const event = Array.from(document.querySelectorAll<HTMLElement>('.family-month-event')).find(item => getComputedStyle(item).getPropertyValue('--family-category-color').trim() !== '33 112 83')!
    const group = document.querySelector<HTMLElement>('.family-month-group')!
    const financeChip = document.querySelector<HTMLElement>('.family-month-chip')!
    return { event: getComputedStyle(event).getPropertyValue('--family-category-color').trim(), group: getComputedStyle(group).getPropertyValue('--family-category-color').trim(), chip: getComputedStyle(financeChip).getPropertyValue('--family-category-color').trim() }
  })
  expect(colors.chip).toBe(colors.group)
  expect(colors.event).not.toBe(colors.chip)
  await page.getByLabel('显示家庭收支与预算', { exact: true }).uncheck()
  await expect(page.locator('.family-month-undated').getByText('本月家庭资金安排', { exact: true })).toHaveCount(0)
  await page.getByLabel('显示家庭收支与预算', { exact: true }).check()
  await page.getByRole('button', { name: `查看 ${date} 的全部 6 项安排`, exact: true }).click()
  await expect(tree.getByText('家庭信用卡 · 还款', { exact: true })).toBeVisible()
  await tree.getByRole('button', { name: /家庭信用卡 · 还款/ }).click()
  await expect(page).toHaveURL(/#assets\/liabilities\/all$/)
  await expect(page.getByRole('rowheader', { name: /家庭信用卡/ })).toBeVisible()
  await page.getByRole('navigation', { name: '家庭空间导航' }).getByRole('button', { name: '我的空间', exact: true }).click()
  await page.screenshot({ path: '.codex-tmp/family-month-calendar-results/desktop.png', fullPage: true })
  const codeResponse = await post('/codes', { label: '月历浏览测试家人' })
  expect(codeResponse.status()).toBe(201)
  const code = await codeResponse.json()
  const phoneContext = await browser.newContext({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, serviceWorkers: 'block', timezoneId: 'Asia/Shanghai' })
  const phone = await phoneContext.newPage()
  phone.on('pageerror', error => errors.push(error.message))
  await phone.goto(`${baseURL}${workspace}`)
  await phone.locator('#family-code').fill(code.loginCode)
  await phone.getByRole('button', { name: '进入家庭空间', exact: true }).click()
  await expect(phone.getByRole('region', { name: '家庭月历', exact: true })).toBeVisible()
  await expect(phone.getByRole('button', { name: '添加安排', exact: true })).toHaveCount(0)
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await phone.getByRole('button', { name: `查看 ${date} 的全部 6 项安排`, exact: true }).click()
  await expect(phone.getByText('亲子活动 4', { exact: true })).toBeVisible()
  await phone.getByRole('button', { name: /亲子活动 4/ }).click()
  await expect(phone.getByLabel('安排名称', { exact: true })).toHaveValue('亲子活动 4')
  await expect(phone.getByLabel('安排名称', { exact: true })).toBeDisabled()
  await expect(phone.getByRole('button', { name: '保存安排', exact: true })).toHaveCount(0)
  await phone.getByRole('button', { name: '查看首页月历', exact: true }).click()
  await phone.screenshot({ path: '.codex-tmp/family-month-calendar-results/phone.png', fullPage: true })
  await phoneContext.close()

  await page.setViewportSize({ width: 375, height: 812 })
  await calendar.getByRole('button', { name: '添加安排', exact: true }).click()
  await expect(page.getByLabel('添加到对应页面')).toBeInViewport()
  await page.getByLabel('添加到对应页面').selectOption('education/activities')
  await page.getByRole('button', { name: '去添加本月安排', exact: true }).click()
  await expect(page.getByLabel('安排名称', { exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '查看首页月历', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 900 })

  await tree.getByRole('button', { name: /周末亲子出游/ }).click()
  await expect(page.getByLabel('安排名称', { exact: true })).toHaveValue('周末亲子出游')
  await page.getByLabel('这项安排已完成', { exact: true }).check()
  await page.getByRole('button', { name: '保存安排', exact: true }).click()
  await expect(page.getByText('已保存到首页月历。', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看首页月历', exact: true }).click()
  await expect(tree.getByRole('button', { name: /周末亲子出游/ })).toHaveCount(0)
  await calendar.getByLabel('显示已完成', { exact: true }).check()
  await expect(tree.getByRole('button', { name: /周末亲子出游/ })).toBeVisible()
  await tree.getByRole('button', { name: /周末亲子出游/ }).click()
  await page.getByRole('button', { name: '删除安排', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '删除安排', exact: true }).click()
  await expect(page.getByText('已删除这项安排。', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
