test('login-state network failure stays closed and can be retried', async ({ page }) => {
  await page.route(`**${FAMILY_WORKSPACE_PATH}/api/session`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '测试网络故障' } }) }))
  await page.goto(FAMILY_WORKSPACE_PATH)
  await expect(page.getByText('暂时无法验证登录状态', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '家人访问管理', exact: true })).toHaveCount(0)
  await page.unroute(`**${FAMILY_WORKSPACE_PATH}/api/session`)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.locator('#family-code')).toBeVisible()
})


