import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { FAMILY_WORKSPACE_PATH } from '../../shared/family-workspace.mjs'

test('administrator and family complete separate real browser sessions at desktop and phone widths', async ({ page, context, browser }) => {
  const errors: string[] = [], authRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().includes('/api/auth/')) authRequests.push(request.url()) })
  await page.goto(FAMILY_WORKSPACE_PATH)
  await expect(page.getByRole('heading', { name: '家庭统筹会', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '进入家庭空间', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '家人访问管理', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '管理员登录' }).click()
  await page.getByLabel('管理员邮箱', { exact: true }).fill('ray@example.test')
  await page.getByRole('button', { name: '获取邮箱验证码', exact: true }).click()
  await expect(page.getByText('请查收验证码', { exact: true })).toBeVisible()
  const delivery = JSON.parse(await readFile(path.resolve('.codex-tmp/family-workspace-browser/test-email.json'), 'utf8'))
  expect(delivery.email).toBe('ray@example.test')
  await page.locator('#family-code').fill(delivery.otp)
  await page.getByLabel('在这台设备上记住登录').check()
  await page.getByRole('button', { name: '登录并管理家庭空间', exact: true }).click()
  await expect(page.getByRole('heading', { name: '欢迎回家，Ray。' })).toBeVisible()
  const ownerCookie = (await context.cookies()).find(cookie => cookie.name === 'hoooho_family_session')!
  expect(ownerCookie.httpOnly).toBe(true)
  expect(ownerCookie.sameSite).toBe('Strict')
  expect(ownerCookie.path).toBe(FAMILY_WORKSPACE_PATH)
  expect(ownerCookie.expires - Date.now() / 1000).toBeGreaterThan(29 * 86400)
  await page.reload()
  await expect(page.getByRole('heading', { name: '欢迎回家，Ray。' })).toBeVisible()
  await page.getByRole('button', { name: '家人访问管理', exact: true }).click()
  await page.getByLabel('家人称呼').fill('妈妈')
  await page.getByRole('button', { name: '生成 30 天登录码', exact: true }).click()
  const generated = page.getByLabel('登录码（仅本次显示）', { exact: true })
  await expect(generated).toBeVisible()
  const code = await generated.inputValue()
  expect(code).toMatch(/^RAY-/)
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: '复制链接和登录码', exact: true }).click()
  await expect(page.getByRole('button', { name: '已复制链接和登录码', exact: true })).toBeVisible()
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  expect(copied).toContain(code)
  expect(copied).toContain(FAMILY_WORKSPACE_PATH)
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/admin-desktop.png', fullPage: true })

  const mobile = await browser.newContext({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' })
  const phone = await mobile.newPage()
  phone.on('pageerror', error => errors.push(error.message))
  await phone.goto(`http://127.0.0.1:4197${FAMILY_WORKSPACE_PATH}`)
  await expect(phone.locator('#family-code')).toBeVisible()
  await phone.screenshot({ path: '.codex-tmp/family-workspace-results/login-mobile.png', fullPage: true })
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await phone.locator('#family-code').fill(code)
  await phone.getByRole('button', { name: '进入家庭空间', exact: true }).click()
  await expect(phone.getByRole('heading', { name: '欢迎回家，妈妈。' })).toBeVisible()
  const memberCookie = (await mobile.cookies()).find(cookie => cookie.name === 'hoooho_family_session')!
  expect(memberCookie.expires).toBe(-1)
  await phone.getByRole('button', { name: '打开导航', exact: true }).click()
  await expect(phone.getByRole('button', { name: '家人访问管理', exact: true })).toHaveCount(0)
  await phone.getByRole('navigation', { name: '家庭空间导航' }).getByRole('button', { name: '家庭日程', exact: true }).click()
  await expect(phone.getByRole('table')).toBeVisible()
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const forbidden = await mobile.request.get(`http://127.0.0.1:4197${FAMILY_WORKSPACE_PATH}/api/codes`)
  expect(forbidden.status()).toBe(403)
  await phone.screenshot({ path: '.codex-tmp/family-workspace-results/member-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(page.getByText('已撤销', { exact: true })).toBeVisible()
  await phone.reload()
  await expect(phone.locator('#family-code')).toBeVisible()
  await phone.locator('#family-code').fill(code)
  await phone.getByRole('button', { name: '进入家庭空间', exact: true }).click()
  await expect(phone.getByText(/登录码无效、已到期或已被撤销/)).toBeVisible()
  await mobile.close()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await page.getByRole('button', { name: '生活总览', exact: true }).click()
  await expect(page.getByRole('heading', { name: '欢迎回家，Ray。' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/admin-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.locator('#family-code')).toBeVisible()
  expect(errors).toEqual([])
  expect(authRequests).toEqual([])
})

test('login-state network failure stays closed and can be retried', async ({ page }) => {
  await page.route(`**${FAMILY_WORKSPACE_PATH}/api/session`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '测试网络故障' } }) }))
  await page.goto(FAMILY_WORKSPACE_PATH)
  await expect(page.getByText('暂时无法验证登录状态', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '家人访问管理', exact: true })).toHaveCount(0)
  await page.unroute(`**${FAMILY_WORKSPACE_PATH}/api/session`)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.locator('#family-code')).toBeVisible()
})
