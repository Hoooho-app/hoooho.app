async function choose(page, moduleTitle: string, pageTitle: string, child?: string) {
  const primary = page.getByRole('navigation', { name: '家庭空间导航', exact: true })
  if (!await primary.isVisible()) await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await primary.getByRole('button', { name: moduleTitle, exact: true }).click()
  await page.getByRole('navigation', { name: `${moduleTitle}二级菜单`, exact: true }).getByRole('link', { name: pageTitle, exact: true }).click()
  if (child) await page.getByRole('navigation', { name: `${pageTitle}三级菜单`, exact: true }).getByRole('link', { name: child, exact: true }).click()
}

test('every secondary and tertiary destination in all nine modules has its own content on desktop and phone', async ({ page }) => {
  test.setTimeout(180_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await mockMember(page)
  for (const width of [1280, 375]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto(FAMILY_WORKSPACE_PATH)
    await expect(page.getByRole('heading', { name: '我的空间', exact: true })).toBeVisible()
    for (const module of workspaceModules) {
      const primary = page.getByRole('navigation', { name: '家庭空间导航', exact: true })
      if (!await primary.isVisible()) await page.getByRole('button', { name: '打开导航', exact: true }).click()
      await primary.getByRole('button', { name: module.title, exact: true }).click()
      const secondary = page.getByRole('navigation', { name: `${module.title}二级菜单`, exact: true })
      await expect(secondary.getByRole('link')).toHaveCount(module.pages.length)
      for (const item of module.pages) {
        await secondary.getByRole('link').filter({ hasText: item.title }).click()
        await expect(secondary.getByRole('link').filter({ hasText: item.title })).toHaveAttribute('aria-current', 'page')
        await expect(page.getByRole('heading', { name: module.title, exact: true })).toBeVisible()
        const tertiary = page.getByRole('complementary', { name: '三级目录', exact: true })
        await expect(tertiary).toHaveCount(item.sections.length ? 1 : 0)
        if (item.sections.length) await expect(tertiary.getByRole('link')).toHaveCount(item.sections.length)
        for (const content of item.sections.length ? item.sections : [item]) {
          if (item.sections.length) {
            await tertiary.getByRole('link', { name: content.title, exact: true }).click()
            await expect(tertiary.getByRole('link', { name: content.title, exact: true })).toHaveAttribute('aria-current', 'page')
          }
          if (item.id === 'policy') await expect(page.getByRole('region', { name: content.title, exact: true })).toBeVisible()
          else await expect(page.getByRole('heading', { name: content.title, exact: true }).first()).toBeVisible()
          if (!content.finance && !['calendar', 'policy'].includes(item.id)) {
            const table = page.getByRole('region', { name: `${content.title}记录表`, exact: true })
            for (const field of content.columns) await expect(table.getByRole('columnheader', { name: field, exact: true })).toBeVisible()
            await expect(table.getByText('暂无记录', { exact: true })).toBeVisible()
          }
          if (content.finance?.view !== 'overview') await expect(page.getByRole('region', { name: '家庭财务核心指标', exact: true })).toHaveCount(0)
          await expect(page.getByRole('link', { name: '财务总览', exact: true })).toHaveCount(0)
          expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
        }
      }
    }
  }
  expect(errors).toEqual([])
})

