import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import path from 'node:path'
import { FAMILY_WORKSPACE_PATH } from '../../shared/family-workspace.mjs'

test('administrator and family complete separate real browser sessions at desktop and phone widths', async ({ page, context, browser }) => {
  const errors: string[] = [], authRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().includes('/api/auth/')) authRequests.push(request.url()) })
  await page.goto(FAMILY_WORKSPACE_PATH)
  await expect(page.getByRole('heading', { name: '家庭统筹会', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '进入家庭空间', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '家人访问管理', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '管理员登录' }).click()
  await page.getByLabel('管理员邮箱', { exact: true }).fill('ray@example.test')
  await page.getByRole('button', { name: '获取邮箱验证码', exact: true }).click()
  await expect(page.getByText('请查收验证码', { exact: true })).toBeVisible()
  const delivery = JSON.parse(await readFile(path.resolve('.codex-tmp/family-workspace-browser/test-email.json'), 'utf8'))
  expect(delivery.email).toBe('ray@example.test')
  await page.locator('#family-code').fill(delivery.otp)
  await page.getByLabel('在这台设备上记住登录').check()
  await page.getByRole('button', { name: '登录并管理家庭空间', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的空间', exact: true })).toBeVisible()
  const ownerCookie = (await context.cookies()).find(cookie => cookie.name === 'hoooho_family_session')!
  expect(ownerCookie.httpOnly).toBe(true)
  expect(ownerCookie.sameSite).toBe('Strict')
  expect(ownerCookie.path).toBe(FAMILY_WORKSPACE_PATH)
  expect(ownerCookie.expires - Date.now() / 1000).toBeGreaterThan(29 * 86400)
  await page.reload()
  await expect(page.getByRole('heading', { name: '我的空间', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '家人访问管理', exact: true }).click()
  await page.getByLabel('家人称呼').fill('妈妈')
  await page.getByRole('button', { name: '生成 30 天登录码', exact: true }).click()
  const generated = page.getByLabel('登录码（仅本次显示）', { exact: true })
  await expect(generated).toBeVisible()
  const code = await generated.inputValue()
  expect(code).toMatch(/^RAY-/)
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: '复制链接和登录码', exact: true }).click()
  await expect(page.getByRole('button', { name: '已复制链接和登录码', exact: true })).toBeVisible()
  const copied = await page.evaluate(() => navigator.clipboard.readText())
  expect(copied).toContain(code)
  expect(copied).toContain(FAMILY_WORKSPACE_PATH)
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/admin-desktop.png', fullPage: true })

  const mobile = await browser.newContext({ viewport: { width: 375, height: 812 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' })
  const phone = await mobile.newPage()
  phone.on('pageerror', error => errors.push(error.message))
  await phone.goto(`http://127.0.0.1:4197${FAMILY_WORKSPACE_PATH}`)
  await expect(phone.locator('#family-code')).toBeVisible()
  await phone.screenshot({ path: '.codex-tmp/family-workspace-results/login-mobile.png', fullPage: true })
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await phone.locator('#family-code').fill(code)
  await phone.getByRole('button', { name: '进入家庭空间', exact: true }).click()
  await expect(phone.getByRole('heading', { name: '我的空间', exact: true })).toBeVisible()
  const memberCookie = (await mobile.cookies()).find(cookie => cookie.name === 'hoooho_family_session')!
  expect(memberCookie.expires).toBe(-1)
  await phone.getByRole('button', { name: '打开导航', exact: true }).click()
  await expect(phone.getByRole('button', { name: '家人访问管理', exact: true })).toHaveCount(0)
  await phone.getByRole('navigation', { name: '家庭空间导航' }).getByRole('button', { name: '日程与生活安排', exact: true }).click()
  await phone.getByRole('navigation', { name: '日程与生活安排二级菜单' }).getByRole('link', { name: '家庭日历', exact: true }).click()
  await expect(phone.getByRole('table')).toBeVisible()
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const forbidden = await mobile.request.get(`http://127.0.0.1:4197${FAMILY_WORKSPACE_PATH}/api/codes`)
  expect(forbidden.status()).toBe(403)
  await phone.screenshot({ path: '.codex-tmp/family-workspace-results/member-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.getByRole('button', { name: '确认撤销', exact: true }).click()
  await expect(page.getByText('已撤销', { exact: true })).toBeVisible()
  await phone.reload()
  await expect(phone.locator('#family-code')).toBeVisible()
  await phone.locator('#family-code').fill(code)
  await phone.getByRole('button', { name: '进入家庭空间', exact: true }).click()
  await expect(phone.getByText(/登录码无效、已到期或已被撤销/)).toBeVisible()
  await mobile.close()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await page.getByRole('button', { name: '我的空间', exact: true }).click()
  await expect(page.getByRole('heading', { name: '我的空间', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/admin-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.locator('#family-code')).toBeVisible()
  expect(errors).toEqual([])
  expect(authRequests).toEqual([])
})

test('login-state network failure stays closed and can be retried', async ({ page }) => {
  await page.route(`**${FAMILY_WORKSPACE_PATH}/api/session`, route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '测试网络故障' } }) }))
  await page.goto(FAMILY_WORKSPACE_PATH)
  await expect(page.getByText('暂时无法验证登录状态', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '家人访问管理', exact: true })).toHaveCount(0)
  await page.unroute(`**${FAMILY_WORKSPACE_PATH}/api/session`)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect(page.locator('#family-code')).toBeVisible()
})


test('nine modules, independent secondary menus, global search and remembered page work at desktop and phone widths', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route(`**${FAMILY_WORKSPACE_PATH}/api/session`, route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ authenticated: true, role: 'member', name: '家人', expiresAt: Date.now() + 3600_000 }) }))
  await page.goto(FAMILY_WORKSPACE_PATH)
  await expect(page.getByRole('heading', { name: '我的空间', exact: true })).toBeVisible()
  const directory = ['家庭收支与预算', '资产负债与投资', '税务法律与传承', '日程与生活安排', '居所物品与家政', '健康与照护', '子女教育与成长', '风险安全与应急', '家庭治理与关系']
  const primary = page.getByRole('navigation', { name: '家庭空间导航' })
  for (const title of directory) {
    await primary.getByRole('button', { name: title, exact: true }).click()
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
    const secondary = page.getByRole('navigation', { name: `${title}二级菜单` })
    await expect(secondary).toBeVisible()
    expect(await secondary.getByRole('link').count()).toBeGreaterThanOrEqual(7)
    await secondary.getByRole('link').last().click()
    await expect(secondary.getByRole('link').last()).toHaveAttribute('aria-current', 'page')
    await expect(page.getByText('暂无记录', { exact: true })).toBeVisible()
  }
  await primary.getByRole('button', { name: '家庭收支与预算', exact: true }).click()
  const financeMenu = page.getByRole('navigation', { name: '家庭收支与预算二级菜单' })
  for (const title of ['收支明细', '预算管理', '固定账单', '现金流计划', '支付账户', '报销与分摊', '收支报表']) await expect(financeMenu.getByRole('link', { name: title, exact: true })).toBeVisible()
  const search = page.getByRole('searchbox', { name: '全局搜索', exact: true })
  await search.fill('房贷')
  const results = page.getByRole('region', { name: '全局搜索结果' })
  await expect(results.getByRole('button', { name: '固定账单', exact: false })).toBeVisible()
  await results.getByRole('button', { name: '负债与还款', exact: false }).click()
  await expect(page).toHaveURL(/#assets\/liabilities$/)
  await expect(page.getByRole('heading', { name: '负债与还款', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: '负债与还款', exact: true })).toBeVisible()
  await page.keyboard.press('Control+k')
  await expect(search).toBeFocused()
  await search.fill('完全不存在的页面')
  await expect(page.getByText('没有找到匹配的页面，请尝试其他关键词。', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(results).not.toBeVisible()
  await search.fill('预算管理')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: '预算管理', exact: true })).toBeVisible()
  const colors = await page.locator('.family-workspace').evaluate(element => {
    const style = getComputedStyle(element)
    return { text: style.color, background: style.backgroundColor, texture: style.getPropertyValue('--hoho-paper-grain').trim() }
  })
  expect(colors).toEqual({ text: 'rgb(24, 24, 24)', background: 'rgb(255, 255, 255)', texture: 'none' })
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/console-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await primary.getByRole('button', { name: '子女教育与成长', exact: true }).click()
  await page.getByRole('navigation', { name: '子女教育与成长二级菜单' }).getByRole('link', { name: '公益与社会参与', exact: true }).click()
  await expect(page.getByRole('heading', { name: '公益与社会参与', exact: true })).toBeVisible()
  const active = page.getByRole('link', { name: '公益与社会参与', exact: true })
  const box = await active.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(375)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await search.fill('保姆')
  await results.getByRole('button', { name: '家政与交接', exact: false }).click()
  await expect(page).toHaveURL(/#home\/domestic$/)
  await expect(page.getByRole('heading', { name: '家政与交接', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.codex-tmp/family-workspace-results/console-mobile.png', fullPage: true })
  await page.getByRole('button', { name: '打开生活助手', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '生活助手' })).toBeVisible()
  await page.getByRole('button', { name: '整理这个月的家庭收支', exact: true }).click()
  await expect(page.getByLabel('消息草稿', { exact: true })).toHaveValue('整理这个月的家庭收支')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '生活助手' })).not.toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(/#education\/community$/)
  await expect(page.getByRole('heading', { name: '公益与社会参与', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
