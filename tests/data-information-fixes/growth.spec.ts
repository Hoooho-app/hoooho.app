import { test, expect } from '@playwright/test'
import { openFirstUseLogin, createFirstChild } from '../helpers/first-child'

test('same-day supplementation, pending review, deletion and reopen retain consistent data', async ({ page }, testInfo) => {
  await openFirstUseLogin(page)
  await page.getByRole('tab', { name: '注册' }).click()
  await page.locator('input').nth(0).fill(`核对${Date.now().toString().slice(-9)}`)
  await page.locator('input').nth(1).fill('fictional-audit-20261103')
  const registered = page.waitForResponse(response => response.url().endsWith('/api/auth/register') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '注册并进入' }).click()
  const registration = await registered
  expect(registration.ok()).toBe(true)
  const session = await registration.json()
  const authHeaders = { Origin: 'http://127.0.0.1:4198', Authorization: `Bearer ${session.token}` }
  await page.waitForURL('**/nurse-station')
  const child = await createFirstChild(page, { name: '虚构小禾', birthday: '2024-01-01', gender: 'female' })
  const day = '2026-10-31', nextDay = '2026-11-01'
  await page.goto('/health-profile/growth')
  for (const [height, weight] of [['84', ''], ['', '11']]) {
    await page.getByRole('button', { name: '添加', exact: true }).click()
    const form = page.getByRole('dialog')
    await form.getByLabel('测量日期').fill(day)
    await form.getByLabel(/（cm）/).fill(height)
    await form.getByLabel('体重（kg）').fill(weight)
    await form.getByRole('button', { name: '保存记录' }).click()
    await expect(form).toHaveCount(0)
  }
  await expect(page.locator('.growth-record-row')).toHaveCount(1)
  await expect(page.locator('.growth-record-row')).toContainText('84.0 cm')
  await expect(page.locator('.growth-record-row')).toContainText('11.0 kg')
  const pending = await page.request.post('/api/growth-measurements', { data: { memberId: child.id, measuredAt: nextDay, measurementType: 'height', heightCm: 120, weightKg: null, dataStatus: 'pending_confirmation' }, headers: authHeaders })
  expect(pending.ok(), await pending.text()).toBe(true)
  await page.goto('/health-profile/basic')
  await expect(page.locator('.growth-data-latest')).toContainText('84.0 cm')
  await expect(page.locator('.growth-interpretation')).not.toContainText('120.0')
  await expect(page.locator('.growth-chart-record')).toHaveCount(1)
  await page.getByRole('button', { name: '记录列表', exact: true }).click()
  const pendingRow = page.locator('.growth-record-row').filter({ hasText: nextDay })
  await expect(pendingRow).toContainText('待确认')
  await pendingRow.getByRole('button', { name: '编辑', exact: true }).click()
  const editor = page.getByRole('dialog')
  await editor.getByLabel(/（cm）/).fill('85')
  await editor.getByLabel('已核对本次测量').check()
  await editor.getByRole('button', { name: '保存记录' }).click()
  await expect(editor).toHaveCount(0)
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await expect(page.locator('.growth-data-latest')).toContainText('85.0 cm')
  await expect(page.locator('.growth-interpretation')).toContainText('增加 1.0 cm')
  await page.reload()
  await expect(page.locator('.growth-data-latest')).toContainText('85.0 cm')
  await page.getByRole('button', { name: '记录列表', exact: true }).click()
  for (const date of [nextDay, day]) {
    page.once('dialog', dialog => dialog.accept())
    await page.locator('.growth-record-row').filter({ hasText: date }).getByRole('button', { name: '删除', exact: true }).click()
    await expect(page.locator('.growth-record-row').filter({ hasText: date })).toHaveCount(0)
  }
  await page.getByRole('button', { name: '返回', exact: true }).click()
  await page.reload()
  await expect(page.locator('.growth-data-latest')).toContainText('暂无记录')
  await expect(page.getByRole('button', { name: '— cm', exact: true })).toBeVisible()
  const member = await (await page.request.get(`/api/members/${child.id}`, { headers: authHeaders })).json()
  expect(member.heightCm).toBeNull(); expect(member.weightKg).toBeNull()
  await page.getByRole('button', { name: '记录列表', exact: true }).click()
  await page.getByRole('button', { name: '添加', exact: true }).click()
  const form = page.getByRole('dialog')
  await expect(form.getByLabel('测量日期')).toHaveAttribute('min', '2024-01-01')
  await form.getByLabel('测量日期').fill('2023-12-31')
  await form.getByLabel(/（cm）/).fill('84')
  await expect(form.getByRole('button', { name: '保存记录' })).toBeDisabled()
  await expect(form.getByRole('alert')).toHaveText('测量日期不能早于出生日期')
  await form.getByLabel('测量日期').fill(day)
  await page.route('**/api/growth-measurements', route => route.request().method() === 'POST' ? route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: '虚构保存失败' } }) }) : route.continue())
  await form.getByRole('button', { name: '保存记录' }).click()
  await expect(form.getByRole('alert')).toBeVisible()
  await expect(form.getByLabel(/（cm）/)).toHaveValue('84')
  await page.screenshot({ path: testInfo.outputPath('input-preserved-after-failure.png') })
})
