import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('another tab acknowledging old events preserves new offline events, and input values never enter telemetry', async ({ page, context, request }) => {
  const fixture = JSON.parse(await readFile('.codex-tmp/analytics-fixture.json', 'utf8'))
  const payloads: string[] = []
  page.on('request', req => { if (req.url().endsWith('/api/analytics/events')) payloads.push(req.postData() || '') })
  await page.addInitScript(() => localStorage.setItem('hoooho:welcome:seen:v1', 'true'))
  await page.route('**/api/analytics/events', route => route.abort())
  await page.goto('/login')
  await expect(page.getByPlaceholder('输入你的昵称')).toBeVisible()
  const keys = () => page.evaluate(() => Object.keys(localStorage).filter(key => key.startsWith('hoooho-behavior-event-v1:')))
  await expect.poll(keys).not.toHaveLength(0)
  const old = await keys()
  const second = await context.newPage()
  await second.clock.install()
  await second.addInitScript(token => sessionStorage.setItem('hoooho-ops-auth-token', token), fixture.ownerToken)
  await second.goto('/ops/marketing?environment=internal')
  await expect(second.getByRole('heading', { name: '产品运营', exact: true })).toBeVisible()
  await page.getByPlaceholder('输入你的昵称').fill('PRIVATE_INPUT_DO_NOT_CAPTURE')
  await page.getByRole('button', { name: '显示密码', exact: true }).click()
  const newKeys = (await keys()).filter(key => !old.includes(key))
  expect(newKeys.length).toBeGreaterThan(0)
  await second.clock.fastForward(16000)
  await expect.poll(async () => (await keys()).some(key => old.includes(key))).toBeFalsy()
  expect((await keys()).filter(key => newKeys.includes(key)).length).toBe(newKeys.length)
  await page.unroute('**/api/analytics/events')
  const delivered = page.waitForResponse(response => response.url().endsWith('/api/analytics/events') && response.status() === 200)
  await page.goto('/help?search=PRIVATE_QUERY_DO_NOT_CAPTURE')
  await delivered
  expect(payloads.join('')).not.toContain('PRIVATE_INPUT_DO_NOT_CAPTURE')
  expect(payloads.join('')).not.toContain('PRIVATE_QUERY_DO_NOT_CAPTURE')
  const response = await request.get('/api/ops/analytics?environment=internal', { headers: { Authorization: 'Bearer ' + fixture.ownerToken } })
  expect(response.ok()).toBeTruthy()
  await second.close()
})

test('actual browser visits and clicks are persisted and readable in the replacement dashboard', async ({ page, request, browser }) => {
  const fixture = JSON.parse(await readFile('.codex-tmp/analytics-fixture.json', 'utf8'))
  const report = async () => (await request.get('/api/ops/analytics?environment=internal', { headers: { Authorization: 'Bearer ' + fixture.ownerToken } })).json()
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('hoooho:welcome:seen:v1', 'true'))
  await page.goto('/login')
  await page.getByPlaceholder('输入你的昵称').fill(fixture.nickname)
  await page.locator('input[name="password"]').fill(fixture.password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/nurse-station/)
  const nav = page.getByRole('navigation', { name: '主要导航', exact: true })
  await nav.getByRole('button', { name: '健康日历', exact: true }).click()
  await expect(page).toHaveURL(/health-events/)
  await nav.getByRole('button', { name: '症状记录', exact: true }).click()
  await page.getByRole('button', { name: '改用文字', exact: true }).click()
  await page.getByRole('button', { name: '日常', exact: true }).click()
  await page.getByRole('group', { name: '记录日常选项' }).getByRole('button', { name: '喂养与饮食', exact: true }).click()
  const form = page.getByRole('dialog', { name: '喂养/饮食', exact: true })
  await form.getByRole('radio', { name: '配方奶', exact: true }).click()
  await form.getByLabel('喂奶量').fill('123')
  let failOnce = true
  await page.route('**/api/quick-records', async route => {
    if (failOnce && route.request().method() === 'POST') { failOnce = false; await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: { code: 'SYNTHETIC_FAILURE', message: '合成保存失败' } }) }) }
    else await route.continue()
  })
  const failed = page.waitForResponse(response => response.url().endsWith('/api/quick-records') && response.status() === 500)
  await form.getByRole('button', { name: '保存记录', exact: true }).click(); await failed
  await expect(form.getByRole('button', { name: '保存记录', exact: true })).toBeEnabled()
  const saved = page.waitForResponse(response => response.url().endsWith('/api/quick-records') && response.status() === 201)
  await form.getByRole('button', { name: '保存记录', exact: true }).click(); await saved
  await expect(form).toHaveCount(0)
  await nav.getByRole('button', { name: '孩子档案', exact: true }).click()
  await expect(page).toHaveURL(/health-profile/)
  await page.goto('/help')
  await expect.poll(async () => (await report()).pages.find((row: { id: string }) => row.id === '/health-events')?.views).toBeGreaterThan(0)
  await expect.poll(async () => (await report()).features.some((row: { name: string; clicks: number }) => row.name === '前往健康日历' && row.clicks > 0)).toBeTruthy()
  await expect.poll(async () => (await report()).features.find((row: { id: string }) => row.id === 'record_save')?.completed).toBe(1)
  const saveStats = (await report()).features.find((row: { id: string }) => row.id === 'record_save')
  expect(saveStats.started).toBe(2); expect(saveStats.failed).toBe(1)
  expect((await report()).features.some((row: { name: string }) => row.name === '喂养/饮食')).toBeTruthy()
  // The reporting administrator uses an independent session from the customer whose activity is measured.
  const adminContext = await browser.newContext({ baseURL: 'http://127.0.0.1:4268', viewport: { width: 1440, height: 1000 }, serviceWorkers: 'block' })
  page = await adminContext.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(token => sessionStorage.setItem('hoooho-ops-auth-token', token), fixture.ownerToken)
  await page.goto('/ops/marketing?project=hoooho&environment=internal')
  await expect(page.getByRole('heading', { name: '产品运营', exact: true })).toBeVisible()
  await expect(page.getByText('近期已收到采集回执', { exact: true })).toBeVisible()
  await expect(page.getByText('页面卖点', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '全页面统计', exact: true }).click()
  await expect.poll(async () => page.getByRole('table').getByRole('row').count()).toBeGreaterThan(60)
  await page.getByLabel('搜索统计条目').fill('关于护护')
  await expect(page.getByRole('table').getByRole('row')).toHaveCount(2)
  await expect(page.getByRole('table')).toContainText('已接入 · 暂无访问')
  await page.getByRole('button', { name: '功能使用', exact: true }).click()
  await expect(page.getByRole('heading', { name: '功能使用与高频操作' })).toBeVisible()
  await expect(page.getByRole('table')).toContainText('前往健康日历')
  await page.getByRole('button', { name: '访问路径', exact: true }).click()
  await expect(page.getByRole('heading', { name: '页面之间怎么走' })).toBeVisible()
  await expect(page.getByRole('table')).toContainText('健康日历')
  await page.getByRole('button', { name: '关键流程', exact: true }).click()
  await expect(page.locator('.analytics-funnels')).toContainText('登录成功')
  await expect(page.locator('.analytics-funnels')).toContainText('1 人')
  await page.reload(); await expect(page.getByRole('heading', { name: '手动记录', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '使用总览', exact: true }).click()
  await page.screenshot({ path: '.codex-tmp/analytics-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  await page.getByRole('button', { name: '全页面统计', exact: true }).click()
  await page.screenshot({ path: '.codex-tmp/analytics-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBeTruthy()
  await page.getByLabel('开始日期').fill('2020-01-01')
  await expect(page.getByRole('alert')).toContainText('统计读取失败')
  await page.getByRole('button', { name: '重置筛选', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByLabel('数据范围').selectOption('internal')
  await expect(page.locator('.analytics-collection')).toContainText('近期已收到采集回执')
  expect(errors).toEqual([])
  // Neither anonymous traffic nor ordinary users may read the private report.
  expect((await request.get('/api/ops/analytics')).status()).toBe(401)
  expect((await request.get('/api/ops/analytics', { headers: { Authorization: 'Bearer ' + fixture.userToken } })).status()).toBe(403)
  await adminContext.close()
})
