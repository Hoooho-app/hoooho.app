import { expect, test } from '@playwright/test'

test('iPhone SE completes autosave, history, curve and reassurance flow without overflow', async ({ page }, testInfo) => {
  await page.goto('/login')
  await page.getByRole('tab', { name: '注册' }).click()
  const inputs = page.locator('input')
  await inputs.nth(0).fill(`验收${Date.now()}`)
  await inputs.nth(1).fill('local-test-0911')
  await page.getByRole('button', { name: '注册并进入' }).click()
  await page.getByRole('button', { name: '添加第一个孩子' }).click()
  await page.getByLabel('姓名').fill('小禾')
  await page.getByLabel('出生日期').fill('2024-01-15')
  await page.getByText('女', { exact: true }).click()
  await page.getByLabel('你是孩子的谁？').selectOption({ label: '妈妈' })
  const memberResponse = page.waitForResponse((response) => response.url().includes('/api/members') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '添加家庭成员' }).click()
  expect((await memberResponse).ok()).toBe(true)
  await page.goto('/health-profile')
  await expect(page.getByText('再补充 2 项，就能生成成长身份卡')).toBeVisible()
  await expect(page.getByRole('button', { name: /记录第一次反应/ })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await page.screenshot({ path: testInfo.outputPath('health-profile-iphone-se.png'), fullPage: true })

  await page.getByRole('button', { name: '铸造成长身份卡' }).click()
  await expect(page.getByText('看看今天长到哪里了')).toBeVisible()
  await expect(page.getByText('填写后自动保存')).toBeVisible()
  await expect(page.getByText('补充更多信息')).toHaveCount(0)
  await expect(page.locator('.growth-mini-charts')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  expect(await page.locator('.growth-inline-blood').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('basic-health-default-iphone-se.png'), fullPage: true })
  await page.getByLabel(/身长|身高/).fill('82')
  await page.getByLabel(/身长|身高/).blur()
  await page.getByRole('spinbutton', { name: /^体重/ }).fill('11.2')
  await page.getByRole('spinbutton', { name: /^体重/ }).blur()
  await page.getByRole('button', { name: 'A型' }).click()
  const dateBeforeRh = await page.locator('.growth-measured-date').boundingBox()
  await page.getByRole('button', { name: /^Rh$/ }).click()
  const dateAfterRh = await page.locator('.growth-measured-date').boundingBox()
  expect(dateAfterRh?.y).toBe(dateBeforeRh?.y)
  await page.getByRole('button', { name: '阳性（Rh+）' }).click()
  await expect(page.getByText(/已保存/)).toBeVisible()
  await expect(page.getByText('今日成长落点')).toBeVisible()
  await expect(page.getByText(/约P|约<P|约>P/).first()).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('basic-health-feedback-iphone-se.png'), fullPage: true })
  await page.getByRole('button', { name: '查看成长记录' }).click()
  await expect(page.getByRole('heading', { name: '成长记录' })).toBeVisible()
  await expect(page.getByText('第一次成长落点已建立')).toBeVisible()
  await page.getByRole('tab', { name: /身长曲线|身高曲线/ }).click()
  await expect(page.locator('.growth-chart-journey')).toBeVisible()
  expect(await page.locator('.growth-chart-record').count()).toBe(1)
  await page.waitForTimeout(2400)
  await expect(page.locator('.growth-chart-journey')).toHaveCount(0)
  await expect(page.locator('.growth-chart-final-avatar')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('growth-curve-iphone-se.png'), fullPage: true })
  await page.getByRole('button', { name: '成长安心解读' }).click()
  await expect(page.getByText('位置偏下，不等于长得不好')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('growth-reassurance-iphone-se.png'), fullPage: true })
  for (const width of [390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/health-profile/basic')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
})
