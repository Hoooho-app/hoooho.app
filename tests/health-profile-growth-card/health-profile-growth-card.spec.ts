import { expect, test } from '@playwright/test'

test('iPhone SE completes a real growth snapshot flow without overflow', async ({ page }, testInfo) => {
  await page.goto('/login')
  await page.getByRole('tab', { name: '注册' }).click()
  const inputs = page.locator('input')
  await inputs.nth(0).fill(`验收${Date.now()}`)
  await inputs.nth(1).fill('local-test-0911')
  await page.getByRole('button', { name: '注册并进入' }).click()
  await page.getByRole('button', { name: '添加第一个孩子' }).click()
  await page.getByLabel('姓名').fill('小禾')
  await page.getByLabel('出生日期').fill('2024-01-15')
  await page.getByText('女', { exact: true }).click()
  await page.getByLabel('你是孩子的谁？').selectOption({ label: '妈妈' })
  await page.getByRole('button', { name: '添加家庭成员' }).click()

  await page.goto('/health-profile')
  await expect(page.getByText('再补充 2 项，就能生成成长身份卡')).toBeVisible()
  await expect(page.getByRole('button', { name: /记录第一次反应/ })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await page.screenshot({ path: testInfo.outputPath('health-profile-iphone-se.png'), fullPage: true })

  await page.getByRole('button', { name: '铸造成长身份卡' }).click()
  const feedback = page.locator('.growth-feedback-bar')
  const collapsedHeight = await feedback.evaluate((element) => element.getBoundingClientRect().height)
  await expect(page.getByRole('button', { name: /补充更多信息/ })).toBeVisible()
  await expect(page.getByRole('button', { name: '填写身高后即可查看' })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  expect(await page.locator('.growth-card-blood-type button').evaluateAll((buttons) => buttons.every((button) => button.getBoundingClientRect().height >= 44))).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('basic-health-default-iphone-se.png'), fullPage: true })
  await page.getByLabel('身高').fill('82')
  await page.getByLabel('身高').blur()
  await expect(page.getByText(/身高 82 cm/)).toBeVisible()
  await expect(page.getByText(/^(?:<P1|>P99|P\d+)$/)).toBeVisible()
  await page.getByRole('spinbutton', { name: /^体重/ }).fill('11.2')
  await page.getByRole('spinbutton', { name: /^体重/ }).blur()
  await page.getByRole('button', { name: 'A型' }).click()
  await page.getByRole('button', { name: 'Rh+' }).click()
  await expect(page.getByText('成长坐标已建立')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('basic-health-feedback-iphone-se.png'), fullPage: true })
  await page.getByRole('button', { name: /补充更多信息/ }).click()
  expect(await feedback.evaluate((element) => element.getBoundingClientRect().height)).toBe(collapsedHeight)
  await page.getByRole('button', { name: /收起更多信息/ }).click()
  await page.getByRole('button', { name: '保存成长快照' }).click()
  await expect(page.getByText('第一组成长坐标已建立')).toBeVisible()
  await expect(page.getByText('A型 Rh+')).toBeVisible()
  await page.waitForTimeout(1100)
  await page.screenshot({ path: testInfo.outputPath('growth-snapshot-iphone-se.png'), fullPage: true })
  await page.getByRole('button', { name: '完成' }).click()
  await expect(page.getByText('成长身份卡已保存，并会用于就医准备')).toBeVisible()
  await expect(page.getByText('已建立')).toBeVisible()
  for (const width of [390, 430]) {
    await page.setViewportSize({ width, height: 844 })
    await page.goto('/health-profile/basic')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  }
})
