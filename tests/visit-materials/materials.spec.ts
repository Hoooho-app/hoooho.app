test('服务端已保存但回包中断时，锁定快照重试只确认同一条资料', async ({ page, request }) => {
  const root = pageRoot(page)
  let dropped = false
  await page.route('**/case-records', async route => {
    const response = await route.fetch()
    if (!dropped) { dropped = true; await route.abort('connectionreset') }
    else await route.fulfill({ response })
  })
  await root.getByLabel('上传照片或问诊截图').setInputFiles(await file())
  await expect(root.locator('.vm-file-row')).toHaveCount(1)
  await root.getByRole('button', { name: '稍后整理，先保存原件', exact: true }).click()
  await expect(root.getByRole('button', { name: '重试保存', exact: true })).toBeEnabled()
  await expect(root.getByRole('button', { name: '继续添加', exact: true })).toBeDisabled()
  await root.getByRole('button', { name: '重试保存', exact: true }).click()
  await expect(root).toContainText('已保存到健康日历')
  const index = await (await request.get('/api/members/' + memberId + '/journal-index', { headers })).json()
  expect(dropped).toBe(true); expect(index.records).toHaveLength(1); expect(index.attachments).toHaveLength(1)
})

test('记录时间复用标准控件，清空保留未知，选择后保存实际时间并拒绝未来', async ({ page, request }) => {
  const root = pageRoot(page), time = root.locator('input[aria-label="记录时间"]')
  await expect(time).toHaveValue('')
  await page.setViewportSize({ width: 320, height: 568 })
  await root.getByRole('button', { name: '补充一句', exact: true }).click()
  await page.locator('textarea[aria-label="补充说明"]').fill('LongNote'.repeat(120))
  await page.getByRole('dialog', { name: '就诊资料操作' }).getByRole('button', { name: '完成', exact: true }).click()
  expect((await root.locator('.vm-supplement-row').boundingBox())!.height).toBeLessThanOrEqual(72)
  expect(await root.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await time.fill('10000-01-01T10:30')
  await expect(time).toHaveAttribute('aria-invalid', 'true')
  await time.fill('2020-01-02T10:30')
  await time.fill('')
  await expect(root.locator('.vm-record-time')).toContainText('资料未注明')
  await root.getByRole('button', { name: '粘贴文字', exact: true }).click()
  await page.getByLabel('粘贴对话内容').fill('虚构资料：就诊时间由家长手动核对。')
  await page.getByRole('button', { name: '添加这段资料', exact: true }).click()
  await time.fill('9999-12-31T10:30')
  await expect(time).toHaveAttribute('aria-invalid', 'true')
  await root.getByRole('button', { name: '稍后整理，先保存原件', exact: true }).click()
  await expect(root).toContainText('请选择不晚于现在的实际就诊时间')
  const empty = await (await request.get('/api/members/' + memberId + '/journal-index', { headers })).json()
  expect(empty.records).toHaveLength(0)
  await time.fill('2020-01-02T10:30')
  await root.getByRole('button', { name: '稍后整理，先保存原件', exact: true }).click()
  await expect(root).toContainText('已保存到健康日历')
  const index = await (await request.get('/api/members/' + memberId + '/journal-index', { headers })).json()
  expect(index.records[0].occurredAt).toBe('2020-01-02T02:30:00.000Z')
  expect(index.records[0].journal.visit.materials.occurredAt).toBe(index.records[0].occurredAt)
  expect(index.records[0].journal.timePrecision).toBe('exact')
})
