test('discard failure stays on the page and retains input for a retry',async({page})=>{
 await page.getByLabel('对话输入').fill('退出失败也应保留')
 await page.route('**/front-desk-record',route=>route.request().method()==='DELETE'?route.fulfill({status:503,json:{error:{code:'TEMPORARILY_UNAVAILABLE',message:'暂不可用'}}}):route.continue())
 await page.getByRole('button',{name:'返回',exact:true}).click()
 await page.getByRole('button',{name:'不保存并退出',exact:true}).click()
 await expect(page.getByRole('dialog').getByRole('alert')).toContainText('退出未完成')
 await expect(page).toHaveURL(/smart-record/)
 await page.unroute('**/front-desk-record')
 await page.getByRole('button',{name:'不保存并退出',exact:true}).click()
 await reenter(page)
 await expect(page.getByLabel('对话输入')).toHaveValue('')
})
