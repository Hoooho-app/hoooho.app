import { expect, test } from '@playwright/test'
import { TokenService } from '../../server/auth/token-service.mjs'

const token = new TokenService('ops-workspace-synthetic-secret', 3_600_000).create({ id: 'synthetic-ops-admin', email: 'ops@example.test' })

test('dates stay in their workflow nodes and build identity; renewal persists and can be cleared', async ({ page, request }) => {
  expect((await request.post('/__test/reset')).ok()).toBeTruthy()
  const api = '/api/ops/workflow/expiry'
  expect((await request.get(api)).status()).toBe(401)
  await page.clock.setFixedTime(new Date('2030-04-01T16:00:00Z'))
  await page.addInitScript(value => sessionStorage.setItem('hoooho-ops-auth-token', value), token)
  await page.goto('/ops/workflow?view=delivery&deliveryProject=hoooho&step=distribution-certificate')
  const dates = page.getByRole('region', { name: '到期与续订' })
  await expect(dates).toContainText('还剩 29 天')
  await dates.getByRole('button', { name: '更新日期' }).click()
  await dates.getByLabel('Apple Distribution 证书到期日').fill('2030-06-01')
  await dates.getByRole('button', { name: '保存日期' }).click()
  await expect(dates.getByRole('status')).toContainText('日期已保存')
  await page.reload()
  await page.getByRole('button', { name: /^GitHub · 签名材料 Secrets/ }).click()
  await expect(dates).toContainText('还剩 60 天')
  await expect(dates.locator('.ops-expiry-row').filter({ hasText: 'App Store 分发描述文件到期日' }).getByLabel('日期未核实')).toBeVisible()
  await dates.getByRole('button', { name: '更新日期' }).click()
  await dates.getByLabel('Apple Distribution 证书到期日').fill('')
  await dates.getByRole('button', { name: '保存日期' }).click()
  await expect(dates).not.toContainText('2030-06-01')
  await page.getByRole('button', { name: /^内测组与测试者/ }).click()
  await expect(dates).toContainText('1.2.0 (18)')
  await page.getByLabel('计划版本号').fill('1.2.0')
  await page.getByRole('button', { name: '新建交付轮次' }).click()
  await page.getByRole('button', { name: /^上传构建/ }).click()
  await expect(dates).toContainText('确认上传回执并登记构建号后可填写')
  await expect(dates).not.toContainText('2030-04-15')
})
test('workflow is navigable from the sidebar, keeps deep links, and distinguishes regional evidence', async ({ page, request }) => {
  expect((await request.post('/__test/reset')).ok()).toBeTruthy()
  await page.addInitScript(value => sessionStorage.setItem('hoooho-ops-auth-token', value), token)
  await page.goto('/ops')
  await page.getByRole('link', { name: '工作流', exact: true }).click()
  const history = page.getByRole('region', { name: '域名注册与迁移', exact: true })
  await expect(history).toContainText('历史转入')
  await history.getByRole('button', { name: '查看链路节点：GoDaddy' }).click()
  await expect(page.getByRole('region', { name: '节点详情' })).toContainText('不承接现有用户流量')
  await expect(page.getByRole('region', { name: 'AI 整理后保存' })).toContainText('确认保存')
  await page.getByRole('button', { name: /^Agent AI 编排/ }).click()
  await expect(page.getByRole('heading', { name: 'Agent AI 编排', exact: true })).toBeFocused()
  await expect(page.getByRole('list', { name: 'Agent AI 所用能力' })).toContainText('松手后完整转写')
  await expect(page.getByRole('list', { name: 'Agent AI 所用能力' })).toContainText('图片、文档与画面识别')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Agent AI 编排', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '海外', exact: true }).click()
  await page.getByRole('button', { name: /^海外独立链路/ }).click()
  await expect(page.getByRole('region', { name: '节点详情' })).toContainText('没有独立海外生产域名')
  await page.getByRole('button', { name: '旧服务 / 保留链路 →', exact: true }).click()
  await expect(page.getByRole('region', { name: '节点详情' })).toContainText('不作为新的海外生产')
  await page.goBack()
  await expect(page.getByRole('heading', { name: '海外独立链路' })).toBeVisible()
  await page.setViewportSize({ width: 375, height: 667 })
  await page.getByRole('button', { name: '生产发布', exact: true }).click()
  await page.getByRole('button', { name: /^TestFlight 内测/ }).click()
  await expect(page.getByRole('region', { name: '节点详情' })).toContainText('普通网页部署不会自动上传')
  expect(await page.locator('.ops-workspace-content').evaluate(el => el.scrollWidth <= el.clientWidth)).toBeTruthy()
  await page.route('**/api/ops/workflow', route => route.fulfill({ status: 503, json: { error: { message: 'synthetic unavailable' } } }))
  await page.getByRole('button', { name: '重新读取' }).click()
  await expect(page.getByRole('alert')).toContainText('上次成功读取的快照')
  await expect(page.getByRole('heading', { name: 'TestFlight 内测', exact: true })).toBeVisible()
})

test('delivery workflow records an admin checkpoint, restores it on reload, and starts a separate round', async ({ page, request }) => {
  expect((await request.post('/__test/reset')).ok()).toBeTruthy()
  const endpoint = '/api/ops/workflow/delivery'
  const nonOwner = new TokenService('ops-workspace-synthetic-secret', 3_600_000).create({ id: 'other', email: 'other@example.test' })
  expect((await request.get(endpoint)).status()).toBe(401)
  expect((await request.post(endpoint, { headers: { Authorization: `Bearer ${nonOwner}` }, data: {} })).status()).toBe(403)
  await page.addInitScript(value => sessionStorage.setItem('hoooho-ops-auth-token', value), token)
  await page.goto('/ops/workflow?view=delivery&deliveryProject=hoooho&step=apple-api-key')
  const detail = page.getByRole('article', { name: '交付节点详情' })
  await expect(detail).toContainText('用户与访问权限 → 集成')
  await detail.getByRole('button', { name: /下一环/ }).click()
  await expect(detail).toContainText('ASC_API_KEY_P8')
  await expect(detail).toContainText('怎样才算完成')
  await detail.getByLabel('本节点状态').selectOption('blocked')
  await detail.getByLabel('卡住原因').selectOption('access')
  await detail.getByRole('button', { name: '保存节点' }).click()
  await expect(page.getByRole('status')).toContainText('节点进度已保存')
  await page.reload()
  await expect(detail).toContainText('账号或权限受限')
  await expect(page.getByText('当前阻塞')).toBeVisible()
  await detail.getByLabel('本节点状态').selectOption('confirmed')
  await detail.getByRole('checkbox').check()
  await detail.getByRole('button', { name: '保存节点' }).click()
  await expect(detail.getByText('变更记录（2）')).toBeVisible()
  await page.getByLabel('计划版本号').fill('1.2.3')
  await page.getByRole('button', { name: '新建交付轮次' }).click()
  await expect(detail).toContainText('本轮交付 · 1.2.3')
  await page.getByRole('button', { name: /^上传构建/ }).click()
  await expect(detail.getByLabel('Apple 构建号')).toBeVisible()
  await page.setViewportSize({ width: 375, height: 667 })
  expect(await page.locator('.ops-workspace-content').evaluate(el => el.scrollWidth <= el.clientWidth)).toBeTruthy()
})
