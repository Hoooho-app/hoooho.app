import { test, expect, type Page } from '@playwright/test'
import { TokenService } from '../../server/auth/token-service.mjs'
const token = new TokenService('ops-workspace-synthetic-secret', 3600000).create({ id: 'synthetic-ops-admin', email: 'ops@example.test' })
const headers = { Authorization: `Bearer ${token}` }
const badge = (page: Page) => page.locator('.ops-sidebar .ops-unread-badge')
async function selectProject(page: Page, id: string, name: string) {
  const select = page.locator('.ops-project-select select')
  if (await select.isVisible()) await select.selectOption(id)
  else await page.locator('.ops-project-tabs').getByRole('button', { name, exact: true }).click()
}
test.beforeEach(async ({ page, request }) => {
  expect((await request.post('/__test/reset')).ok()).toBeTruthy()
  await page.addInitScript(token => { sessionStorage.setItem('hoooho-ops-auth-token', token) }, token)
})
test('fluid layout uses ultrawide space and reflows on notebooks without horizontal overflow', async ({ page }, info) => {
  for (const [width, height] of [[2560, 1080], [1440, 900], [1280, 800]]) {
    await page.setViewportSize({ width, height })
    await page.goto('/ops')
    await expect(badge(page)).toHaveText('4')
    await expect(page.getByRole('heading', { name: 'Overview', exact: true })).toBeVisible()
    await expect(page.locator('.ops-account-bar')).toContainText('管理员')
    await expect(page.locator('.ops-account-bar .ops-project-picker')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
    expect(await page.locator('.ops-workspace-content').evaluate(element => element.clientWidth)).toBeGreaterThan(width - 300)
    if (width > 1500) await expect(page.getByRole('complementary', { name: '动态摘要' })).toBeVisible()
    else await expect(page.getByRole('complementary', { name: '动态摘要' })).toBeHidden()
    await page.screenshot({ path: info.outputPath(`synthetic-overview-${width}.png`) })
  }
})
test('preview stays unread; precise feedback navigation persists the receipt and new supplements reappear', async ({ page, request }) => {
  await page.goto('/ops')
  await expect(badge(page)).toHaveText('4')
  const preview = page.getByRole('button', { name: '预览 合成：情况单导出显示问题', exact: true })
  await preview.click()
  expect((await (await request.get('/api/ops/overview', { headers })).json()).unreadCount).toBe(4)
  await page.getByRole('link', { name: '打开并定位 合成：情况单导出显示问题', exact: true }).click()
  await expect(page.locator('.ops-feedback-detail-header h2')).toHaveText('合成：情况单导出显示问题')
  await expect(badge(page)).toHaveText('3')
  await page.goto('/ops'); await page.reload()
  await expect(badge(page)).toHaveText('3')
  await page.getByRole('tab', { name: '已查看', exact: true }).click()
  await expect(page.locator('.ops-event-row')).toHaveCount(1)
  await request.post('/__test/supplement')
  await page.reload()
  await expect(badge(page)).toHaveText('4')
  await expect(page.locator('.ops-event-row').filter({ hasText: '合成：情况单导出显示问题' })).toContainText('新回复')
  await expect(page.getByRole('heading', { name: '更早未查看' })).toBeVisible()
})
test('failed source loading does not acknowledge the event', async ({ page, request }) => {
  const seed = await (await request.get('/__test/seed')).json()
  await page.route(`**/api/ops/feedback/${seed.first}`, route => route.fulfill({ status: 503, json: { error: { code: 'SYNTHETIC_UNAVAILABLE', message: '合成：详情暂时不可用' } } }))
  await page.goto('/ops')
  await expect(badge(page)).toHaveText('4')
  await page.getByRole('link', { name: '打开并定位 合成：情况单导出显示问题', exact: true }).click()
  await expect(page.getByText('反馈详情读取失败', { exact: true })).toBeVisible()
  await expect(badge(page)).toHaveText('4')
  expect((await (await request.get('/api/ops/overview', { headers })).json()).unreadCount).toBe(4)
})
test('billing switches source panels and counters by project, retaining the snapshot actions', async ({ page }, info) => {
  await page.goto('/ops/billing')
  await expect(page.locator('.ops-source-card')).toHaveCount(9)
  await selectProject(page, 'family', '家庭统筹')
  await expect(page.locator('.ops-source-card')).toHaveCount(1)
  await expect(page.locator('.ops-source-card h3')).toHaveText('家庭费用（合成）')
  await expect(page.locator('.ops-summary article').first().locator('strong')).toHaveText('1')
  await expect(page.getByRole('link', { name: '打开原平台' })).toBeVisible()
  await page.locator('.ops-source-card footer').getByRole('button', { name: '查看大图' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: info.outputPath('synthetic-project-billing.png') })
  await selectProject(page, 'qinggan', '翻旧账')
  await expect(page.getByRole('heading', { name: '该项目暂无费用来源' })).toBeVisible()
  await expect(page.locator('.ops-source-card')).toHaveCount(0)
})
test('billing event locates its actual source and only confirms after the snapshot loads', async ({ page, request }) => {
  const data = await (await request.get('/api/ops/overview', { headers })).json()
  const event = data.events.find((item: any) => item.projectId === 'family')
  await page.goto(event.target)
  await expect(page.locator('.ops-source-card[data-target=true]')).toContainText('家庭费用（合成）')
  await expect(page.locator('.ops-source-card[data-target=true] .ops-snapshot img')).toBeVisible()
  await expect(badge(page)).toHaveText('3')
})
