import { expect, test } from '@playwright/test'
import { TokenService } from '../../server/auth/token-service.mjs'
import { finishNursingQuestions, waitForNurseReply } from '../helpers/nursing-interview'

const token = new TokenService('visit-sheet-e2e-secret', 3600000).create({ id: 'visit-test' })
const headers = { Authorization: `Bearer ${token}` }
let memberId: string

test.beforeEach(async ({ page, request }) => {
  const profile = await request.patch('/api/account/profile', { headers, data: { nickname: '刘磊' } })
  expect(profile.ok()).toBe(true)
  const response = await request.post('/api/members', { headers, data: { name: '刘景一', relationship: 'child', birthday: '2024-10-01', gender: 'female' } })
  expect(response.ok()).toBe(true)
  memberId = (await response.json()).id
  await request.get('http://127.0.0.1:4198/success')
  await page.addInitScript(({ token, memberId }) => {
    sessionStorage.setItem('hoooho-auth-token', token)
    localStorage.setItem('hoooho-app', JSON.stringify({ state: { authUser: { id: 'visit-test', nickname: '刘磊' }, currentMemberId: memberId, members: [], profile: null }, version: 5 }))
  }, { token, memberId })
  await page.goto('/nurse-station')
  await expect(page.getByRole('button', { name: '切换记录对象', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '按住记录症状', exact: true })).toBeEnabled()
})

