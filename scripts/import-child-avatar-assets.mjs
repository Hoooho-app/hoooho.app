import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { copyFile, mkdir, readdir, readFile, rm, stat, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const root = process.cwd()
const sourceRoot = path.resolve(process.argv[2] ?? '')
const targetDirectory = path.join(root, 'public', 'avatars', 'children', 'v1')
const generatedModule = path.join(root, 'src', 'generated', 'childAvatarAssets.ts')
const variants = ['east-asian', 'european', 'african']
const expectedIds = ['boy', 'girl'].flatMap((gender) => (
  Array.from({ length: 8 }, (_, age) => variants.map((variant) => `${gender}-age${age}-${variant}`))
)).flat().sort()

assert.notEqual(sourceRoot, root, 'Pass the extracted Hoooho avatar package directory as the first argument.')
const sourceFiles = (await Promise.all(['boys', 'girls'].map(async (directory) => (
  (await readdir(path.join(sourceRoot, directory))).map((file) => path.join(sourceRoot, directory, file))
)))).flat().sort()
assert.equal(sourceFiles.length, 48, 'The final child avatar package must contain exactly 48 files.')

const sourceIds = sourceFiles.map((file) => path.basename(file, '.webp')).sort()
assert.deepEqual(sourceIds, expectedIds, 'The final package must contain every age, gender, and variant exactly once.')

for (const file of sourceFiles) {
  const metadata = await sharp(file).metadata()
  const bytes = (await stat(file)).size
  assert.equal(metadata.format, 'webp', `${file} must be WebP.`)
  assert.equal(metadata.width, 256, `${file} must be 256px wide.`)
  assert.equal(metadata.height, 256, `${file} must be 256px tall.`)
  assert.ok(bytes >= 20 * 1024 && bytes <= 60 * 1024, `${file} must be between 20 and 60 KiB.`)
}

await mkdir(targetDirectory, { recursive: true })
for (const file of await readdir(targetDirectory)) {
  if (file.endsWith('.webp')) await rm(path.join(targetDirectory, file))
}

const entries = []
for (const sourceFile of sourceFiles) {
  const id = path.basename(sourceFile, '.webp')
  const data = await readFile(sourceFile)
  const hash = createHash('sha256').update(data).digest('hex').slice(0, 10)
  const outputFile = `${id}.${hash}.webp`
  await copyFile(sourceFile, path.join(targetDirectory, outputFile))
  entries.push([id, `/avatars/children/v1/${outputFile}`])
}

entries.sort(([left], [right]) => left.localeCompare(right))
const moduleSource = `// Generated by scripts/import-child-avatar-assets.mjs.\n` +
  `// Final 256px child avatars are emitted as content-hashed WebP files.\n` +
  `export const childAvatarAssetPaths = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const\n`
await mkdir(path.dirname(generatedModule), { recursive: true })
await writeFile(generatedModule, moduleSource)
console.log(`Imported ${entries.length} final child avatars.`)
