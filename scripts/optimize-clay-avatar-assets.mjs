import { createHash } from 'node:crypto'
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const root = process.cwd()
const assetDirectory = path.join(root, 'public', 'avatars', 'clay', 'v1')
const generatedModule = path.join(root, 'src', 'generated', 'clayAvatarAssets.ts')
const initialFiles = await readdir(assetDirectory)
const sourceFiles = initialFiles.filter((file) => file.endsWith('.png')).sort()

for (const sourceFile of sourceFiles) {
  const id = sourceFile.replace(/\.png$/, '')
  const sourcePath = path.join(assetDirectory, sourceFile)
  const webp = await sharp(sourcePath)
    .rotate()
    .resize(512, 512, { fit: 'fill' })
    .webp({ quality: 90, alphaQuality: 100, effort: 6, smartSubsample: true })
    .toBuffer()
  const hash = createHash('sha256').update(webp).digest('hex').slice(0, 10)
  const outputFile = `${id}.${hash}.webp`
  const obsoleteFiles = (await readdir(assetDirectory)).filter((file) => file.startsWith(`${id}.`) && file.endsWith('.webp'))
  await Promise.all(obsoleteFiles.map((file) => rm(path.join(assetDirectory, file))))
  await writeFile(path.join(assetDirectory, outputFile), webp)
}

await Promise.all(sourceFiles.map((file) => rm(path.join(assetDirectory, file))))
const entries = (await readdir(assetDirectory))
  .filter((file) => /\.[a-f0-9]{10}\.webp$/.test(file))
  .sort()
  .map((file) => [file.replace(/\.[a-f0-9]{10}\.webp$/, ''), `/avatars/clay/v1/${file}`])
await mkdir(path.dirname(generatedModule), { recursive: true })
const moduleSource = `// Generated by scripts/optimize-clay-avatar-assets.mjs.\n` +
  `// Complete 512px avatars are emitted as content-hashed transparent WebP files.\n` +
  `export const clayAvatarAssetPaths = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const\n`
await writeFile(generatedModule, moduleSource)

const totalBytes = (await Promise.all(entries.map(async ([, url]) => {
  const data = await readFile(path.join(root, 'public', url.replace(/^\//, '')))
  return data.byteLength
}))).reduce((sum, size) => sum + size, 0)

console.log(`Optimized ${sourceFiles.length} new source files; mapped ${entries.length} clay avatars (${(totalBytes / 1024).toFixed(1)} KiB total).`)
