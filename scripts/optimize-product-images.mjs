import { readdir, readFile, writeFile, rm } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import path from 'node:path'
import sharp from 'sharp'

const root = process.cwd()
const hash = data => createHash('sha256').update(data).digest('hex').slice(0, 10)
async function walk(dir) {
  const out = []
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...await walk(file))
    else out.push(file)
  }
  return out
}
const replacements = new Map(), publicPaths = {}, inventory = []
async function optimize(file, width, budget, rename = false) {
  const original = await readFile(file)
  if (rename && /\.[a-f0-9]{10}\.webp$/.test(file)) { const meta = await sharp(original).metadata(); if (meta.width === width && original.length <= budget) return }
  let data
  for (const quality of [80, 74, 68, 62]) {
    let pipeline = sharp(original).rotate().resize({ width, withoutEnlargement: true })
    if (file.includes('/avatars/children/')) pipeline = pipeline.composite([{ input: Buffer.from('<svg width="256" height="256"><path fill="white" d="M0 0h12v12H0zM244 0h12v12h-12zM0 244h12v12H0zM244 244h12v12h-12z"/></svg>') }])
    data = await pipeline.webp({ quality, effort: 6, alphaQuality: 95 }).toBuffer()
    if (data.length <= budget) break
  }
  if (data.length > budget) throw new Error(`Image exceeds budget: ${file} (${data.length})`)
  const base = file.replace(/(?:\.[a-f0-9]{10})?\.(?:png|jpe?g|webp)$/i, '')
  const output = `${base}.${hash(data)}.webp`
  await writeFile(output, data)
  if (rename) { replacements.set(path.basename(file), path.basename(output)); await rm(file) }
  else if (file.includes('/public/')) publicPaths['/' + path.relative(path.join(root, 'public'), file)] = '/' + path.relative(path.join(root, 'public'), output)
  else replacements.set(path.basename(file), path.basename(output))
  inventory.push({ source: path.relative(root, file), output: path.relative(root, output), before: original.length, after: data.length })
}
for (const group of ['children', 'clay']) {
  const dir = path.join(root, 'public/avatars', group, 'v1')
  for (const file of await walk(dir)) if (file.endsWith('.webp')) await optimize(file, 256, 16 * 1024, true)
}
for (const file of await walk(path.join(root, 'src/assets'))) {
  if (/\.(png|jpe?g)$/i.test(file)) await optimize(file, file.includes('food-label-camera') ? 960 : 768, 80 * 1024)
  else if (file.includes('/avatars/') && file.endsWith('.webp')) await optimize(file, 256, 16 * 1024, true)
}
for (const directory of ['public/body-locator', 'public/nurse-triage', 'public/tutorials/add-to-home-screen']) {
  for (const file of await walk(path.join(root, directory))) {
    if (/\.(png|jpe?g)$/i.test(file)) {
      const metadata = await sharp(file).metadata()
      // Preserve atlas coordinates and calibrated medical-location hit areas.
      await optimize(file, directory.includes('body-locator') ? metadata.width : 960, directory.includes('body-locator') ? 200 * 1024 : 80 * 1024)
    }
  }
}
for (const file of await walk(path.join(root, 'src'))) {
  if (!/\.(tsx?|css)$/.test(file) || /\.test\./.test(file)) continue
  let content = await readFile(file, 'utf8')
  for (const [before, after] of replacements) content = content.replace(new RegExp('(?<=[/\"\'])' + before.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'), 'g'), after)
  for (const [before, after] of Object.entries(publicPaths)) content = content.split(before).join(after)
  await writeFile(file, content)
}
await writeFile(path.join(root, 'src/generated/optimizedPublicImages.ts'), `// Generated by scripts/optimize-product-images.mjs. Original calibrated assets are retained.\nexport const optimizedPublicImages: Record<string, string> = ${JSON.stringify(publicPaths, null, 2)}\n`)
